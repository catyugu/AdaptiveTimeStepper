#!/usr/bin/env python3
"""Record and validate the COMSOL thermoelastic trajectory; standard library only."""

from __future__ import annotations

import argparse
import csv
import itertools
import math
import re
from pathlib import Path

from common import ROOT, run_comsol


def write_reference(directory: Path) -> None:
    batch = (directory / "batch.log").read_text(encoding="utf-8", errors="replace")
    version = re.search(r"COMSOL ([0-9.]+) progress", batch)
    if not version or re.search(r"\*Error\*|Exception", batch):
        raise SystemExit("COMSOL batch log is incomplete or contains an error")
    with (directory / "thermoelastic.csv").open(newline="") as stream:
        rows = [
            [
                float(row[key])
                for key in ("time", "x", "v", "theta", "dx", "dv", "dtheta")
            ]
            for row in csv.DictReader(stream)
        ]
    if (
        len(rows) < 3
        or rows[0][0] != 0.0
        or rows[-1][0] != 5.0
        or not all(math.isfinite(value) for row in rows for value in row)
        or not all(a[0] < b[0] for a, b in itertools.pairwise(rows))
    ):
        raise SystemExit("invalid COMSOL trajectory")

    worst_state = worst_derivative = 0.0
    previous_energy = math.inf
    for t, x, v, theta, dx, dv, dtheta in rows:
        a, b, c = math.exp(-t), math.exp(-2 * t), math.exp(-3 * t)
        exact = (a + 0.5 * b + 0.25 * c, -a - b - 0.75 * c, a - b - 0.25 * c)
        derivative = (-a - b - 0.75 * c, a + 2 * b + 2.25 * c, -a + 2 * b + 0.75 * c)
        worst_state = max(
            worst_state, *(abs(y - z) for y, z in zip((x, v, theta), exact))
        )
        worst_derivative = max(
            worst_derivative,
            *(abs(y - z) for y, z in zip((dx, dv, dtheta), derivative)),
        )
        energy = 2 * x * x + 0.5 * v * v + 0.5 * theta * theta
        if energy > previous_energy + 1e-10:
            raise SystemExit("COMSOL reference violates energy dissipation")
        previous_energy = energy
    if worst_state > 1e-5 or worst_derivative > 3e-5:
        raise SystemExit(
            f"COMSOL analytic check failed: {worst_state=}, {worst_derivative=}"
        )

    log = (directory / "thermoelastic.log").read_text(
        encoding="utf-8", errors="replace"
    )
    decisions = re.findall(
        r"^[ \t]*(\d+)[ \t]+[0-9.eE+-]+[ \t]+[0-9.eE+-]+[ \t]+(?:out[ \t]+)?"
        r"\d+[ \t]+\d+[ \t]+\d+[ \t]+([1-5])[ \t]+(\d+)[ \t]+(\d+)[ \t]+",
        log,
        re.MULTILINE,
    )
    if not decisions or int(decisions[-1][0]) != len(rows) - 1:
        raise SystemExit("COMSOL solver log and exported sample count disagree")
    steps, _, rejected, failed = decisions[-1]
    output = [
        f"// COMSOL {version[1]}; generated by tools/comsol/run_thermoelastic.py.",
        "// Raw COMSOL getPVals/getU/getUDot data; q0=x, q1=v, q2=theta.",
        "// SPDX-License-Identifier: MIT",
        "// clang-format off",
        "#pragma once",
        "#include <array>",
        "namespace comsol_thermoelastic {",
        "struct Sample { double time; std::array<double, 3> state, derivative; };",
        f"inline constexpr int accepted_steps = {steps};",
        f"inline constexpr int rejected_steps = {rejected};",
        f"inline constexpr int failed_solves = {failed};",
        f"inline constexpr std::array<Sample, {len(rows)}> samples {{{{",
    ]
    for row in rows:
        output.append(
            "  {"
            + repr(row[0])
            + ", {"
            + ", ".join(map(repr, row[1:4]))
            + "}, {"
            + ", ".join(map(repr, row[4:]))
            + "}},"
        )
    output.extend(["}};", "} // namespace comsol_thermoelastic", ""])
    target = ROOT / "test" / "reference" / "comsol_thermoelastic.hpp"
    with target.open("w", newline="\n") as stream:
        stream.write("\n".join(output))
    print(
        f"{len(rows)} COMSOL samples; analytic errors: state={worst_state:.3e}, derivative={worst_derivative:.3e}"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--directory", type=Path, required=True)
    parser.add_argument("--header-only", action="store_true")
    args = parser.parse_args()
    args.directory.mkdir(parents=True, exist_ok=True)
    if not args.header_only:
        run_comsol(
            args.directory,
            ROOT / "tools/comsol/GeThermoelasticTransient.java",
            "THERMOELASTIC_OK",
        )
    write_reference(args.directory)


if __name__ == "__main__":
    main()
