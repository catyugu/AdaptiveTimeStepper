#!/usr/bin/env python3
"""Record COMSOL's second-order equation for the time-dependent solver.

    python tools/comsol/run_second_order.py --directory .cache/comsol-order
    python tools/comsol/run_second_order.py --header-only --directory .cache/comsol-order

The record is one second-order global equation, ``qtt+0.1*qt+q=0`` with
``q(0)=1`` and ``q'(0)=100``, whose velocity is two orders of magnitude above
the state. Whether COMSOL's error test covers that velocity moves the first step
by sqrt(2), which is what the header pins.

Only regeneration needs COMSOL. The evidence document and the C++ header use the
recorded run.
"""

from __future__ import annotations

import argparse
import csv
import itertools
import math
import re
import tempfile
from pathlib import Path

from common import ROOT, run_comsol

SOURCE = ROOT / "tools" / "comsol" / "GeSecondOrder.java"
HEADER = ROOT / "test" / "reference" / "comsol_second_order.hpp"
CASE = "second_order"
# Step, time, stepsize, out, residual, Jacobian, solves, order, Tfail, NLfail.
LOG_ROW = re.compile(
    r"^[ \t]*(\d+)[ \t]+([-0-9.eE+]+)[ \t]+([-0-9.eE+]+)[ \t]+(out)?[ \t]*"
    r"\d+[ \t]+\d+[ \t]+\d+[ \t]*([1-5])?[ \t]+(\d+)[ \t]+(\d+)[ \t]+",
    re.MULTILINE,
)


def read_case(directory: Path) -> tuple[list[tuple[float, float, float]], list[int]]:
    with (directory / f"{CASE}.csv").open(newline="", encoding="utf-8") as stream:
        rows = list(csv.reader(stream))
    if rows[0] != ["time", "u0", "d0"]:
        raise SystemExit(f"unexpected export columns: {rows[0]}")
    samples = [tuple(float(value) for value in row) for row in rows[1:]]
    if (
        len(samples) < 20
        or samples[0][0] != 0.0
        or not all(math.isfinite(value) for sample in samples for value in sample)
        or not all(a[0] < b[0] for a, b in itertools.pairwise(samples))
    ):
        raise SystemExit("invalid second-order record")
    log = (directory / f"{CASE}.log").read_text(encoding="utf-8", errors="replace")
    found = LOG_ROW.findall(log)
    if not found:
        raise SystemExit("the solver log has no step rows")
    if [int(row[0]) for row in found] != list(range(len(found))):
        raise SystemExit("the solver log is sampled, not complete")
    accepted, rejected, failed = int(found[-1][0]), int(found[-1][5]), int(found[-1][6])
    # The velocity is two orders of magnitude above the state, so the first step
    # has to be the small one; a large first step would mean the export is not
    # the run this header was measured on.
    if samples[1][0] > 1e-3:
        raise SystemExit(f"unexpected first step: {samples[1][0]:.3e}")
    return samples, [accepted, rejected, failed]


def write_header(directory: Path) -> None:
    batch_log = (directory / "batch.log").read_text(encoding="utf-8", errors="replace")
    version_match = re.search(r"COMSOL ([0-9.]+) progress", batch_log)
    if not version_match:
        raise SystemExit("COMSOL version missing from batch log")
    version = version_match.group(1)
    samples, counters = read_case(directory / "secondorder")
    output = [
        f"// COMSOL {version}, GeSecondOrder.java: qtt+0.1*qt+q=0, q(0)=1, q'(0)=100.",
        "// Generated by run_second_order.py from getPVals/getU/getUDot and the solver log.",
        "// Raw doubles and solver-log counters; no library-generated samples.",
        "//",
        "// COMSOL carries no separate variable for the auxiliary velocity, so the",
        "// record is the state alone: the velocity is checked through the decisions",
        "// it drives, not through its values (doc/evidence/second-order.md).",
        "// SPDX-License-Identifier: MIT",
        "// clang-format off",
        "#pragma once",
        "#include <vector>",
        "namespace comsol_second_order {",
        "struct Sample { double time; double value; double derivative; };",
        f"inline constexpr int accepted_steps = {counters[0]};",
        f"inline constexpr int rejected_steps = {counters[1]};",
        f"inline constexpr int failed_solves = {counters[2]};",
        "inline const std::vector<Sample>& samples() {",
        "    static const std::vector<Sample> all {",
    ]
    output.extend(
        "        {" + ", ".join(repr(value) for value in sample) + "}," for sample in samples
    )
    output.extend(["    }; return all;", "}", "} // namespace comsol_second_order", ""])
    text = "\n".join(output)
    candidate = directory / "comsol_second_order.hpp"
    with candidate.open("w", newline="\n", encoding="utf-8") as stream:
        stream.write(text)
    if HEADER.is_file() and HEADER.read_text(encoding="utf-8") != text:
        raise SystemExit(
            f"{HEADER.relative_to(ROOT)} differs from this run; "
            f"the new bytes are in {candidate}, nothing was overwritten"
        )
    with HEADER.open("w", newline="\n", encoding="utf-8") as stream:
        stream.write(text)
    print(f"{HEADER.relative_to(ROOT)}: {len(samples)} samples")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--header-only",
        action="store_true",
        help="regenerate the header from a recorded run",
    )
    parser.add_argument(
        "--directory", type=Path, help="directory for the COMSOL run and raw evidence"
    )
    args = parser.parse_args()
    if args.header_only and args.directory is None:
        parser.error("--header-only requires --directory")
    if args.directory is None:
        with tempfile.TemporaryDirectory(prefix="atstep-second-order-") as temporary:
            directory = Path(temporary)
            run_comsol(directory, SOURCE, "ALL_CASES_OK")
            write_header(directory)
    else:
        args.directory.mkdir(parents=True, exist_ok=True)
        if not args.header_only:
            run_comsol(args.directory, SOURCE, "ALL_CASES_OK")
        write_header(args.directory)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())